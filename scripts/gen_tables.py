"""Generate Unicode tables used by termstage-core.

Run from the repo root:  python scripts/gen_tables.py

Outputs:
  crates/termstage-core/src/text/arabic_table.rs   Arabic presentation forms (from Python's unicodedata)
  crates/termstage-core/src/gfx/diacritics.rs      Kitty Unicode-placeholder row/column diacritics
"""

from __future__ import annotations

import unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALEFS = (0x0622, 0x0623, 0x0625, 0x0627)
FORMS = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}


def arabic() -> str:
    letters: dict[int, list[int]] = defaultdict(lambda: [0, 0, 0, 0])
    lam_alef: dict[int, list[int]] = defaultdict(lambda: [0, 0])
    # Forms-B first: it is what most monospace fonts (e.g. DejaVu Sans Mono) cover.
    ranges = list(range(0xFE70, 0xFF00)) + list(range(0xFB50, 0xFE00))
    for cp in ranges:
        decomposition = unicodedata.decomposition(chr(cp)).split()
        if len(decomposition) < 2 or decomposition[0] not in FORMS:
            continue
        form = FORMS[decomposition[0]]
        bases = [int(x, 16) for x in decomposition[1:]]
        if len(bases) == 1 and not unicodedata.combining(chr(bases[0])):
            if unicodedata.category(chr(bases[0])) == "Lo" and letters[bases[0]][form] == 0:
                letters[bases[0]][form] = cp
        elif len(bases) == 2 and bases[0] == 0x0644 and bases[1] in ALEFS and form in (0, 1):
            lam_alef[bases[1]][form] = cp

    lines = [
        (
            "// @generated by scripts/gen_tables.py from Python's unicodedata "
            f"(Unicode {unicodedata.unidata_version}). Do not edit."
        ),
        "",
        "/// `(letter, [isolated, final, initial, medial])`; 0 = form does not exist.",
        "pub const FORMS: &[(char, [u32; 4])] = &[",
    ]
    for base in sorted(letters):
        forms = letters[base]
        if forms[0] == 0:
            continue
        lines.append(
            f"    ('\\u{{{base:04X}}}', [{', '.join(f'0x{f:04X}' for f in forms)}]), "
            f"// {unicodedata.name(chr(base))}"
        )
    lines += [
        "];",
        "",
        "/// `(alef variant, [isolated, final])` ligature with a preceding lam.",
        "pub const LAM_ALEF: &[(char, [u32; 2])] = &[",
    ]
    for alef in sorted(lam_alef):
        iso, fin = lam_alef[alef]
        lines.append(
            f"    ('\\u{{{alef:04X}}}', [0x{iso:04X}, 0x{fin:04X}]), // {unicodedata.name(chr(alef))}"
        )
    lines += ["];", ""]
    return "\n".join(lines)


def diacritics() -> str:
    src = ROOT / "scripts" / "kitty-rowcolumn-diacritics.txt"
    cps = [
        line.split(";")[0]
        for line in src.read_text().splitlines()
        if line and not line.startswith("#")
    ]
    body = "\n".join(
        "    " + " ".join(f"'\\u{{{cp}}}'," for cp in cps[i : i + 8]) for i in range(0, len(cps), 8)
    )
    return (
        "// @generated by scripts/gen_tables.py from kitty's rowcolumn-diacritics.txt. Do not edit.\n\n"
        "/// Combining marks that encode row/column numbers in Kitty Unicode placeholders.\n"
        f"pub const DIACRITICS: [char; {len(cps)}] = [\n{body}\n];\n"
    )


if __name__ == "__main__":
    out = ROOT / "crates/termstage-core/src"
    (out / "text").mkdir(exist_ok=True)
    (out / "gfx").mkdir(exist_ok=True)
    (out / "text/arabic_table.rs").write_text(arabic())
    (out / "gfx/diacritics.rs").write_text(diacritics())
    print("wrote text/arabic_table.rs and gfx/diacritics.rs")
